export function assistantClient(base:string,token='') {
  const prefix=base.replace(/\/$/,'');
  const headers=()=>({...token?{Authorization:`Bearer ${token}`}:{}});
  async function request<T>(path:string,body?:unknown):Promise<T> {
    let response:Response;
    try {
      response=await fetch(`${prefix}/api/assistant${path}`,{method:body===undefined?'GET':'POST',credentials:'same-origin',headers:{...headers(),...body!==undefined?{'Content-Type':'application/json'}:{}},body:body!==undefined?JSON.stringify(body):undefined,signal:AbortSignal.timeout(85000)});
    } catch {throw new Error('Não foi possível acessar o assistente. Confira a conexão e tente novamente.');}
    const data=await response.json().catch(()=>null);
    if(response.status===401)window.dispatchEvent(new Event('lastro:session-expired'));
    if(!response.ok)throw new Error(data?.error?.message||(response.status===404?'O assistente ainda não está disponível neste ambiente.':'Não foi possível concluir a consulta. Tente novamente.'));
    return data as T;
  }
  async function source(path:string,label:string) {
    // Sources are generated by server tools, not model-authored URLs.
    if(!/^\/api\/(?:documents\/[^/]+\/original|runs\/[^/]+(?:\/outputs\/[^/]+)?)$/.test(path))throw new Error('Fonte indisponível.');
    const response=await fetch(`${prefix}${path}`,{credentials:'same-origin',headers:headers(),signal:AbortSignal.timeout(25000)});
    if(response.status===401)window.dispatchEvent(new Event('lastro:session-expired'));
    if(!response.ok)throw new Error('Não foi possível abrir a fonte. Entre novamente ou tente outra vez.');
    const blob=await response.blob();
    const url=URL.createObjectURL(blob);
    const anchor=document.createElement('a');anchor.href=url;anchor.download=label.includes('.')?label:`${label}.json`;anchor.click();
    setTimeout(()=>URL.revokeObjectURL(url),10000);
  }
  return {request,source};
}
